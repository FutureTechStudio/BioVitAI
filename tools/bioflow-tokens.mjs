import fs from 'node:fs/promises';
import ts from 'typescript';
import { Buffer } from 'node:buffer';
import { format } from 'prettier';
const raw = await fs.readFile('shared/design-tokens/src/index.ts', 'utf8');
const js = ts.transpileModule(raw, {
  compilerOptions: { module: ts.ModuleKind.ESNext },
}).outputText;
const { bioflow } = await import(
  'data:text/javascript;base64,' + Buffer.from(js).toString('base64')
);
const vars = Object.entries(bioflow.color).map(
  ([key, value]) => `  --bf-${key}: ${value};`,
);
for (const group of ['radius', 'space', 'motion'])
  for (const [key, value] of Object.entries(bioflow[group]))
    vars.push(
      `  --bf-${group}-${key}: ${value}${group === 'motion' ? 'ms' : 'px'};`,
    );
const css = await format(
  '/* Generated by tools/bioflow-tokens.mjs. Edit shared/design-tokens/src/index.ts. */\n:root {\n' +
    vars.join('\n') +
    '\n}\n',
  { parser: 'css' },
);
const file = 'apps/web/app/bioflow-tokens.css';
if (process.argv.includes('--check')) {
  if ((await fs.readFile(file, 'utf8')) !== css)
    throw Error('BioFlow CSS tokens are out of sync');
} else await fs.writeFile(file, css);
